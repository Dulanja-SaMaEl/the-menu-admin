<?php

namespace App\Http\Controllers;

use App\Models\User;
use App\Models\Order;
use Illuminate\Http\Request;

class CustomerController extends Controller
{
    /**
     * Display a listing of registered customers with luxury SaaS KPI metrics and filters.
     */
    public function index(Request $request)
    {
        if (auth()->user()?->role === 'Chef') {
            abort(403, 'Unauthorized. Chefs are not allowed to access Customer Management.');
        }

        $search = trim($request->input('search', ''));
        $filter = $request->input('filter', 'all'); // all, active, recurring, new
        $roleFilter = $request->input('role', '');

        $adminRoles = ['Super Admin', 'System Admin', 'HR', 'Chef'];

        // Base query for customers
        $customerBase = User::query();

        // Check if explicit 'Customer' role exists in the DB
        $hasCustomerRole = User::where('role', 'Customer')->exists();

        if (!empty($roleFilter) && $roleFilter !== 'all') {
            $customerBase->where('role', $roleFilter);
        } elseif ($hasCustomerRole) {
            $customerBase->where('role', 'Customer');
        } else {
            // Exclude administrative staff by default
            $nonStaffCount = User::where(function ($q) use ($adminRoles) {
                $q->whereNotIn('role', $adminRoles)
                  ->orWhereNull('role');
            })->count();

            if ($nonStaffCount > 0) {
                $customerBase->where(function ($q) use ($adminRoles) {
                    $q->whereNotIn('role', $adminRoles)
                      ->orWhereNull('role');
                });
            }
        }

        // Calculate KPI Metrics across the entire customer base
        $totalCustomers = (clone $customerBase)->count();
        $activeCustomers = (clone $customerBase)->has('orders')->count();
        $recurringCustomers = (clone $customerBase)->has('orders', '>=', 2)->count();

        // Customer Lifetime Value (Total revenue generated by these customers)
        $customerIds = (clone $customerBase)->pluck('id');
        $totalCustomerSpend = Order::whereIn('user_id', $customerIds)->sum('total_price');
        $avgSpendPerCustomer = $totalCustomers > 0 ? ($totalCustomerSpend / $totalCustomers) : 0;

        $stats = [
            'total_customers'        => $totalCustomers,
            'active_customers'       => $activeCustomers,
            'recurring_customers'    => $recurringCustomers,
            'total_customer_spend'   => $totalCustomerSpend,
            'avg_spend_per_customer' => $avgSpendPerCustomer,
        ];

        // Build query for the listing table
        $query = (clone $customerBase)
            ->withCount('orders')
            ->withSum(['orders as total_spent' => function ($q) {
                $q->whereIn('status', ['completed', 'delivered', 'processing', 'pending']);
            }], 'total_price')
            ->with(['orders' => function ($q) {
                $q->latest()->limit(1);
            }]);

        // Search Filter
        if (!empty($search)) {
            $query->where(function ($q) use ($search) {
                $q->where('name', 'like', "%{$search}%")
                  ->orWhere('email', 'like', "%{$search}%")
                  ->orWhere('phone', 'like', "%{$search}%")
                  ->orWhere('address', 'like', "%{$search}%")
                  ->orWhere('dinner_address', 'like', "%{$search}%");
            });
        }

        // Activity / Segment Filters
        if ($filter === 'active') {
            $query->has('orders');
        } elseif ($filter === 'recurring') {
            $query->has('orders', '>=', 2);
        } elseif ($filter === 'new') {
            $query->where('created_at', '>=', now()->subDays(30));
        }

        $customers = $query->latest()->paginate(15)->withQueryString();

        return view('customers.index', compact(
            'customers',
            'stats',
            'search',
            'filter',
            'roleFilter'
        ));
    }

    /**
     * Remove the specified customer account.
     */
    public function destroy(User $customer)
    {
        if (auth()->user()?->role === 'Chef') {
            abort(403);
        }

        if ($customer->id === auth()->id()) {
            return back()->with('warning', 'You cannot delete your own account.');
        }

        $name = $customer->name;
        $customer->delete();

        return redirect()->route('customers.index')->with('success', "Customer '{$name}' account removed successfully.");
    }
}
